/**
 * The /proposal deck: a visual walkthrough of the M&P Flow demo.
 *
 * The reader has no time to click through the live demo, so the deck *is* the
 * tour. Every slide is a headline, ONE big picture or diagram, and at most
 * three short numbered captions. No paragraphs.
 *
 * Every string the deck renders lives in this file — captions, diagram labels,
 * alt text, button labels — so copy is edited in one place and one lint can
 * police all of it. `scripts/check-proposal-copy.mjs` imports this module and
 * enforces:
 *
 *   - the banned vocabulary (never name the customer's current software, and
 *     never use engineering words: API, webhook, integration, sync, database…),
 *   - headline at most 10 words,
 *   - each caption at most 25 words,
 *   - at most 3 captions per slide,
 *   - under 60 words of body text per slide (everything but kicker and
 *     headline; alt text is scanned for banned words but not counted).
 *
 * Screenshots under /proposal/*.png come from the demo itself and are
 * regenerated by `node scripts/capture-proposal-shots.mjs`.
 */

/** A numbered badge drawn over a screenshot, positioned in percent of the picture box. */
export interface Mark {
  n: number
  /** 0–100, from the left edge of the picture. */
  x: number
  /** 0–100, from the top edge of the picture. */
  y: number
}

/** A numbered caption. `n` matches the badge on the picture when there is one. */
export interface Caption {
  n: number
  text: string
}

/** One step in the five-step trial strip. */
export interface StripStep {
  label: string
}

export type SlideVisual =
  /** A screenshot of the running demo, with numbered badges over it. */
  | { kind: 'shot'; src: string; alt: string; marks?: readonly Mark[] }
  /** Today: one shipment, seen in pieces across three places. */
  | {
      kind: 'diagram'
      name: 'today'
      alt: string
      channels: readonly { label: string; line: string }[]
      centre: string
    }
  /** The trial beside the system they use today. */
  | {
      kind: 'diagram'
      name: 'two-systems'
      alt: string
      here: string
      hereSub: string
      there: string
      thereSub: string
      arrow: string
    }
  /** The discovery session and the three paths a fact can take. */
  | { kind: 'diagram'; name: 'discovery'; alt: string; source: string; options: readonly string[] }
  /** The trial drawn as a strip of numbered steps. */
  | { kind: 'strip'; steps: readonly StripStep[] }
  /** The four asks, drawn as numbered cards. */
  | { kind: 'asks'; items: readonly string[] }
  /** A big link out to the live demo. */
  | { kind: 'link'; href: string; label: string; note: string }
  /** Title slide: the headline carries it. */
  | { kind: 'none' }

export interface Slide {
  /** URL slug: /proposal?slide=<id>. Stable when slides are reordered. */
  id: string
  /** Small label above the headline, e.g. "Your concern". */
  kicker?: string
  /** At most ten words. */
  title: string
  /** One short line under the headline. */
  lead?: string
  visual: SlideVisual
  /** At most three, each at most 25 words. */
  captions?: readonly Caption[]
  /** A small line at the foot of the slide. */
  note?: string
  /** Charcoal background with white text. Only the title slide uses it. */
  tone?: 'dark' | 'light'
}

