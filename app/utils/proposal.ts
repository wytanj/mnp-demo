export function slideIndexById(id: unknown): number {
  const i = PROPOSAL_SLIDES.findIndex((s) => s.id === id)
  return i === -1 ? 0 : i
}

/**
 * Every string a slide renders on screen, minus the kicker and headline.
 * Alt text is excluded: it is scanned for banned words separately, but it is
 * not body copy and does not count against the 60-word budget.
 */
export function slideBodyStrings(slide: Slide): string[] {
  const out: string[] = []
  if (slide.lead) out.push(slide.lead)

  const v = slide.visual
  if (v.kind === 'diagram' && v.name === 'today') {
    for (const c of v.channels) out.push(c.label, c.line)
    out.push(v.centre)
  } else if (v.kind === 'diagram' && v.name === 'two-systems') {
    out.push(v.here, v.hereSub, v.there, v.thereSub, v.arrow)
  } else if (v.kind === 'diagram' && v.name === 'discovery') {
    out.push(v.source, ...v.options)
  } else if (v.kind === 'strip') {
    out.push(...v.steps.map((s) => s.label))
  } else if (v.kind === 'asks') {
    out.push(...v.items)
  } else if (v.kind === 'link') {
    out.push(v.label, v.note)
  }

  for (const c of slide.captions ?? []) out.push(c.text)
  if (slide.note) out.push(slide.note)
  return out
}

/** Alt text on a slide's picture or diagram — scanned for banned words, never counted. */
export function slideAltStrings(slide: Slide): string[] {
  return slide.visual.kind === 'shot' || slide.visual.kind === 'diagram' ? [slide.visual.alt] : []
}

/** Words in a piece of copy. */
export function countWords(text: string): number {
  return text.trim().split(/\s+/).filter(Boolean).length
}

/** Body words on a slide: the 60-word budget the deck is written to. */
export function slideBodyWords(slide: Slide): number {
  return slideBodyStrings(slide).reduce((n, s) => n + countWords(s), 0)
}
